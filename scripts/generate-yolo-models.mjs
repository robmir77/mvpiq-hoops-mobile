// scripts/generate-yolo-models.mjs
//
// Generates src/vision/yoloModels.ts from assets/models/*.tflite.
// The numeric input size is read from the filename, e.g.:
//   ball_rimV8_640_float16.tflite -> 640
//
// Metro/Expo needs static require() calls, so the generated registry is the
// bridge between the filesystem and the React Native bundle.

import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const modelsDir = path.join(root, 'assets', 'models')
const outputFile = path.join(root, 'src', 'vision', 'yoloModels.ts')

const files = fs.readdirSync(modelsDir)
  .filter(name => name.toLowerCase().endsWith('.tflite'))
  .filter(name => /_\d+(?:_|\.tflite$)/i.test(name))
  .sort((a, b) => a.localeCompare(b))

if (!files.length) {
  throw new Error(`No .tflite YOLO models found in ${modelsDir}`)
}

const entries = files.map(fileName => {
  const match = fileName.match(/_(\d+)(?:_|\.tflite$)/i)
  if (!match) throw new Error(`Cannot determine input size from model name: ${fileName}`)

  const inputSize = Number(match[1])
  const id = fileName.replace(/\.tflite$/i, '')
  // YOLOv8 detection heads normally use strides 8/16/32.
  // Use ceil() for non-multiple-of-32 inputs (e.g. 720), matching
  // convolutional feature-map sizing instead of rejecting the model.
  const outputDetections = [8, 16, 32]
    .reduce((sum, stride) => sum + Math.ceil(inputSize / stride) ** 2, 0)
  const pretty = id
    .replace(/_/g, ' · ')
    .replace(/float16/i, 'FP16')
    .replace(/float32/i, 'FP32')
    .replace(/int8/i, 'INT8')

  return `  {
    id: ${JSON.stringify(id)},
    fileName: ${JSON.stringify(fileName)},
    label: ${JSON.stringify(pretty)},
    inputSize: ${inputSize},
    outputDetections: ${outputDetections},
    asset: require(${JSON.stringify(`../../assets/models/${fileName}`)}),
  },`
}).join('\n')

const content = `// AUTO-GENERATED by scripts/generate-yolo-models.mjs
// Do not edit manually.

export interface YoloModelConfig {
  id: string
  fileName: string
  label: string
  inputSize: number
  outputDetections: number
  asset: any
}

export const YOLO_MODELS: YoloModelConfig[] = [
${entries}
]

export const DEFAULT_YOLO_MODEL_ID = YOLO_MODELS[0]?.id ?? ''

export function getYoloModel(modelId?: string): YoloModelConfig | null {
  return YOLO_MODELS.find(m => m.id === modelId) ?? YOLO_MODELS[0] ?? null
}
`

fs.mkdirSync(path.dirname(outputFile), { recursive: true })
fs.writeFileSync(outputFile, content, 'utf8')
console.log(`Generated ${outputFile} with ${files.length} model(s).`)
